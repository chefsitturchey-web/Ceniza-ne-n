"""Read alpha bounds and write atlas metadata. Never modifies source images."""
import json
from pathlib import Path
from collections import deque
from PIL import Image, ImageFilter

ROOT = Path(__file__).resolve().parents[1]
ATLASES = {'assets/units/field_atlas_v3.png': (4, 2),
           'assets/structures/civic_atlas_v3.png': (2, 2),
           'assets/structures/industrial_atlas_v2.png': (2, 2)}


def main_component_bounds(alpha):
    """Ignore stray pixels and a neighbouring sprite crossing a cell boundary."""
    original = alpha.point(lambda value: 255 if value >= 96 else 0).tobytes()
    mask = bytearray(alpha.point(lambda value: 255 if value >= 96 else 0).filter(ImageFilter.MaxFilter(5)).tobytes())
    width, height = alpha.size
    best_count, best = 0, None
    for start, value in enumerate(mask):
        if not value:
            continue
        queue = deque([start])
        mask[start] = 0
        count = 0
        left, top, right, bottom = width, height, 0, 0
        while queue:
            point = queue.popleft()
            x, y = point % width, point // width
            if original[point]:
                count += 1
                left, top, right, bottom = min(left, x), min(top, y), max(right, x + 1), max(bottom, y + 1)
            for neighbour in (point - 1 if x else -1, point + 1 if x + 1 < width else -1,
                              point - width if y else -1, point + width if y + 1 < height else -1):
                if neighbour >= 0 and mask[neighbour]:
                    mask[neighbour] = 0
                    queue.append(neighbour)
        if count > best_count:
            best_count, best = count, (left, top, right, bottom)
    return best


def main():
    sources = dict(ATLASES)
    sources.update({str(p.relative_to(ROOT)).replace('\\', '/'): (1, 1)
                    for p in (ROOT / 'assets/structures/fortress').glob('*.png')})
    result = {}
    for path, (columns, rows) in sources.items():
        image = Image.open(ROOT / path).convert('RGBA')
        width, height = image.size
        regions = []
        for index in range(columns * rows):
            left, top = index % columns * width // columns, index // columns * height // rows
            right, bottom = (index % columns + 1) * width // columns, (index // columns + 1) * height // rows
            alpha = image.getchannel('A').crop((left, top, right, bottom))
            bounds = main_component_bounds(alpha)
            if not bounds:
                raise ValueError('Empty sprite: ' + path)
            x, y, end_x, end_y = bounds
            regions.append([left + x, top + y, end_x - x, end_y - y])
        result['res://' + path] = regions
    (ROOT / 'data/art_bounds.json').write_text(json.dumps(result, indent=2) + '\n', encoding='utf-8')
    (ROOT / 'data/art_bounds.gd').write_text('extends RefCounted\n# Generated by tools/measure_art.py; source images are unchanged.\nconst REGIONS: Dictionary = ' + json.dumps(result, indent=2) + '\n', encoding='utf-8')
    print('Measured', len(sources), 'textures; source images unchanged')


if __name__ == '__main__':
    main()
